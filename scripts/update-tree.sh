#!/usr/bin/env bash
#
# scripts/update-tree.sh — Loop B snapshot of docs/tree.txt
#
# Not an every-edit step. Run when someone asks to update the tree, sync
# docs, or prepare a push (see .cursor/rules/doc-sync.mdc). Ordinary coding
# updates the colocated README and leaves this file alone.
#
# Usage:  ./scripts/update-tree.sh   (or: npm run tree)
#
# The annotated room map docs/tree.md is maintained by hand, and only when
# a top-level folder or a named room appears or disappears.
#
# Notes:
#  - Requires `tree` (brew install tree).
#  - `tree -I` matches a name anywhere, so the ignore list is only names
#    that are asset or build trees. `data` is not ignored: that would hide
#    `lib/data`. `screenshots` hides `docs/screenshots` and no source folder.
#  - Do not read the generated file into a chat. Folder READMEs own file lists.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if ! command -v tree >/dev/null 2>&1; then
  echo "error: 'tree' is not installed. Install with: brew install tree" >&2
  exit 1
fi

# Asset dumps and build output. Names only — see the header note on `data`.
IGNORE='node_modules|.git|.next|.mobile-build|out|dist|build|coverage|test-results|playwright-report|.turbo|.vercel|ios|android|animalsrcs|public|designrefs|clockbgssrc|gems|litrefs|screenshots'
OUT="docs/tree.txt"

{
  echo "# Source and docs snapshot. Generated by npm run tree (scripts/update-tree.sh)."
  echo "# Loop B only — not part of an ordinary code change. Do not hand-edit."
  echo "# Omitted asset and build trees: node_modules .git .next .mobile-build out dist build coverage test-results playwright-report .turbo .vercel ios android animalsrcs public designrefs clockbgssrc gems litrefs docs/screenshots."
  echo "# public/ holds fonts, orbs, folders, friend-pack, gems, pcb, planets, pen-tray. designrefs/ is the moodboard. ios/ is the Capacitor build."
  echo "# Room map: docs/tree.md. Per-file lists live in folder READMEs."
  echo
  tree -I "$IGNORE" --charset=UTF-8 --noreport -n .
} > "$OUT"

lines="$(wc -l < "$OUT" | tr -d ' ')"
if ! grep -q "app" "$OUT" || ! grep -q "components" "$OUT" || ! grep -q "lib" "$OUT"; then
  echo "error: $OUT is missing app, components, or lib — refusing this snapshot" >&2
  exit 1
fi

echo "Wrote $OUT ($lines lines)."
