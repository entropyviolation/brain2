const NAME_SCENE_FITS: { test: RegExp; fit: Partial<FriendPersonality> }[] = [
  { test: /hyrax|marten|sable/, fit: NAMED_FRIEND_PERSONALITY_FITS["pack-00f0350b6374"]! },
  { test: /polecat|ferret/, fit: NAMED_FRIEND_PERSONALITY_FITS["tiny-cute-striped-polecat"]! },
  { test: /\bbat\b/, fit: NAMED_FRIEND_PERSONALITY_FITS.mouse! },
  { test: /turtle|tortoise/, fit: NAMED_FRIEND_PERSONALITY_FITS.skunk! },
]

export function personalityFitFor(animalId: string, displayName = ""): Partial<FriendPersonality> | undefined {
  const id = animalId.trim().toLowerCase()
  if (id && NAMED_FRIEND_PERSONALITY_FITS[id]) return NAMED_FRIEND_PERSONALITY_FITS[id]
  const slug = fitKey(animalId, displayName)
  if (slug && NAMED_FRIEND_PERSONALITY_FITS[slug]) return NAMED_FRIEND_PERSONALITY_FITS[slug]
  const hay = `${animalId} ${displayName}`.toLowerCase()
  for (const row of NAME_SCENE_FITS) {
    if (row.test.test(hay)) return row.fit
  }
  return undefined
}
