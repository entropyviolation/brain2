import type { FriendPersonality } from "@/lib/baby-animal-personality"

function fitKey(animalId: string, displayName = ""): string {
  const fromName = displayName
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48)
  return animalId.trim().toLowerCase() || fromName
}

