export type GsIconName = keyof typeof PATHS

/** Inline SVG for one icon. `title` makes it readable; otherwise it is decorative. */
export function gsIcon(name: GsIconName, title?: string): string {
  const a11y = title ? `role="img" aria-label="${title}"` : 'aria-hidden="true"'
  const tip = title ? `<title>${title}</title>` : ""
  return `<svg class="gs-icon" viewBox="0 0 24 24" width="1em" height="1em" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${tip}${PATHS[name]}</svg>`
}

/** The same icon as a CSS mask URL, for a pseudo-element. */
export function gsIconMask(name: GsIconName): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${PATHS[name]}</svg>`
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`
}
