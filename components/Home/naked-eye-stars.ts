/** Mean obliquity of the ecliptic at J2000, degrees. */
const OBLIQUITY_DEG = 23.4392911
const OBLIQUITY = OBLIQUITY_DEG * DEG
const COS_OBL = Math.cos(OBLIQUITY)
const SIN_OBL = Math.sin(OBLIQUITY)

export type EclipticDirection = {
  /** Unit vector. +x is the vernal equinox, +z is ecliptic north. */
  x: number
  y: number
  z: number
  /** Degrees, 0–360. */
  lon: number
  /** Degrees, positive north. */
  lat: number
}

function wrap360(deg: number): number {
  const x = deg % 360
  return x < 0 ? x + 360 : x
}

/** Equatorial J2000 → mean ecliptic of J2000. Same sense as the planet chart. */
export function eclipticOf(raDeg: number, decDeg: number): EclipticDirection {
  const ra = raDeg * DEG
  const dec = decDeg * DEG
  const xEq = Math.cos(dec) * Math.cos(ra)
  const yEq = Math.cos(dec) * Math.sin(ra)
  const zEq = Math.sin(dec)
  const x = xEq
  const y = yEq * COS_OBL + zEq * SIN_OBL
  const z = -yEq * SIN_OBL + zEq * COS_OBL
  return {
    x,
    y,
    z,
    lon: wrap360(Math.atan2(y, x) / DEG),
    lat: Math.asin(Math.min(1, Math.max(-1, z))) / DEG,
  }
}

/**
 * Glass the orrery already uses. Tilt matches `toScreen`. The limb is a
 * unit direction, just outside Neptune's √r orbit (~186 px), not kilometres.
 * `north` lifts ecliptic latitude. It is not the chart's z×8 AU term.
 */
export const ORRERY_SKY = {
  cx: 260,
  cy: 200,
  w: 520,
  h: 400,
  limb: 216,
  tilt: 0.72,
  north: 100,
} as const

export function projectDirection(
  dir: Pick<EclipticDirection, "x" | "y" | "z">,
  glass: Pick<typeof ORRERY_SKY, "cx" | "cy" | "limb" | "tilt" | "north"> = ORRERY_SKY,
): { x: number; y: number } {
  return {
    x: glass.cx + dir.x * glass.limb,
    y: glass.cy + dir.y * glass.limb * glass.tilt - dir.z * glass.north,
  }
}

/** Small circle. Brighter stars are larger, in the same range as the old dots. */
export function starRadius(mag: number): number {
  const radius = 1.05 - mag * 0.15
  return Math.min(1.35, Math.max(0.5, Math.round(radius * 100) / 100))
}

/** Chart star blue. A0 (B−V 0) stays this color; other spectra lean off it. */
const GLASS = [0xcf, 0xe8, 0xff] as const
const GLASS_WEIGHT = 0.58
const BV_TINT: readonly (readonly [number, number, number, number])[] = [
  [-0.4, 148, 176, 255],
  [-0.2, 176, 198, 255],
  [0.0, 207, 232, 255],
  [0.35, 242, 220, 228],
  [0.7, 255, 206, 186],
  [1.1, 255, 176, 140],
  [1.5, 255, 146, 108],
  [2.0, 255, 120, 88],
]

function tintAt(bv: number): [number, number, number] {
  const t = Math.min(BV_TINT[BV_TINT.length - 1][0], Math.max(BV_TINT[0][0], bv))
  let i = 1
  while (i < BV_TINT.length - 1 && BV_TINT[i][0] < t) i++
  const a = BV_TINT[i - 1]
  const b = BV_TINT[i]
  const u = (t - a[0]) / (b[0] - a[0] || 1)
  return [a[1] + (b[1] - a[1]) * u, a[2] + (b[2] - a[2]) * u, a[3] + (b[3] - a[3]) * u]
}

function hexByte(n: number): string {
  return Math.round(n).toString(16).padStart(2, "0")
}

/** Pale fill. The glass blue still owns the dot; B−V only tints it. */
export function starFill(bv: number): string {
  const [r, g, b] = tintAt(bv)
  const mix = (channel: number, glass: number) => channel * (1 - GLASS_WEIGHT) + glass * GLASS_WEIGHT
  return `#${hexByte(mix(r, GLASS[0]))}${hexByte(mix(g, GLASS[1]))}${hexByte(mix(b, GLASS[2]))}`
}

export type SkyStarDot = {
  hip: number
  name: string
  x: number
  y: number
  r: number
  fill: string
  mag: number
}

/** One dot per catalog star, fixed on the glass. */
export function skyStarDots(glass: typeof ORRERY_SKY = ORRERY_SKY): SkyStarDot[] {
  return NAKED_EYE_STARS.map((star) => {
    const at = projectDirection(eclipticOf(star.ra, star.dec), glass)
    return {
      hip: star.hip,
      name: star.name,
      x: Math.round(at.x * 10) / 10,
      y: Math.round(at.y * 10) / 10,
      r: starRadius(star.mag),
      fill: starFill(star.bv),
      mag: star.mag,
    }
  })
}

export const SKY_STAR_DOTS = skyStarDots()
