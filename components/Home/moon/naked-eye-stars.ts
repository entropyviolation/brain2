const C2_NM_K = 1.4388e7

function planck(nm: number, kelvin: number): number {
  const exponent = C2_NM_K / (nm * kelvin)
  const raised = exponent > 80 ? Number.POSITIVE_INFINITY : Math.exp(exponent)
  return 1 / (nm ** 5 * (raised - 1))
}

function xyzOf(kelvin: number): [number, number, number] {
  let x = 0
  let y = 0
  let z = 0
  for (let i = 0; i < CMF.length; i++) {
    const energy = planck(380 + i * 5, kelvin)
    const row = CMF[i]
    x += energy * row[0]
    y += energy * row[1]
    z += energy * row[2]
  }
  return [x, y, z]
}

function encodeSrgb(channel: number): number {
  const c = Math.min(1, Math.max(0, channel))
  return c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055
}

function decodeSrgb(channel: number): number {
  const c = Math.min(1, Math.max(0, channel))
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
}

/** Kelvin from B−V (Ballesteros 2012), clamped to the stellar range. */
export function starTemperature(bv: number): number {
  const x = Math.min(2, Math.max(-0.4, bv))
  return 4600 * (1 / (0.92 * x + 1.7) + 1 / (0.92 * x + 0.62))
}

/** Cooler than F5, open the blackbody chroma so orange and red still read. */
function chromaOf(bv: number): number {
  const x = Math.min(2, Math.max(-0.4, bv))
  if (x <= 0.45) return 1
  return 1 + (x - 0.45) * 0.85
}

function hexByte(n: number): string {
  return Math.min(255, Math.max(0, Math.round(n))).toString(16).padStart(2, "0")
}

/**
 * Blackbody sRGB for a B−V index. The brightest channel is full;
 * magnitude is carried by size and opacity, not by this hex.
 */
export function starFill(bv: number): string {
  const [X, Y, Z] = xyzOf(starTemperature(bv))
  let r = 3.2404542 * X - 1.5371385 * Y - 0.4985314 * Z
  let g = -0.969266 * X + 1.8760108 * Y + 0.041556 * Z
  let b = 0.0556434 * X - 0.2040259 * Y + 1.0572252 * Z
  r = Math.max(0, r)
  g = Math.max(0, g)
  b = Math.max(0, b)
  const peak = Math.max(r, g, b)
  if (!(peak > 0)) return "#ffffff"
  r /= peak
  g /= peak
  b /= peak
  const sat = chromaOf(bv)
  const R = Math.min(1, Math.max(0, 1 - (1 - encodeSrgb(r)) * sat))
  const G = Math.min(1, Math.max(0, 1 - (1 - encodeSrgb(g)) * sat))
  const B = Math.min(1, Math.max(0, 1 - (1 - encodeSrgb(b)) * sat))
  const lin = [decodeSrgb(R), decodeSrgb(G), decodeSrgb(B)]
  const peak2 = Math.max(...lin) || 1
  return `#${lin.map((channel) => hexByte(encodeSrgb(channel / peak2) * 255)).join("")}`
}

/** Main-sequence color index used only when Hipparcos left B−V blank. */
const CLASS_BV: Readonly<Record<string, number>> = {
  O: -0.33,
  B: -0.2,
  A: 0,
  F: 0.35,
  G: 0.65,
  K: 1.15,
  M: 1.6,
}

/** B−V for color. A missing index uses the spectral-class letter. */
export function colorIndex(bv: number | null, spect: string): number {
  if (bv != null && Number.isFinite(bv)) return bv
  return CLASS_BV[spect.trim().charAt(0).toUpperCase()] ?? 0
}

/** Disk radius on the glass. Brighter stars are larger. */
export function starRadius(mag: number): number {
  const flux = 10 ** (-0.4 * mag)
  return Math.min(2.5, Math.round((0.36 + 1.02 * flux ** 0.4) * 100) / 100)
}

/** Brighter stars burn clearer. Magnitude 5 stays a dim speck. */
export function starOpacity(mag: number): number {
  const t = Math.min(1, Math.max(0, (mag + 1.5) / (5 + 1.5)))
  return Math.round((1 - 0.7 * t ** 0.85) * 100) / 100
}

/** Half-arm of the diffraction cross. Magnitude 1 and fainter have none. */
export function starCross(mag: number): number {
  if (!(mag < 1)) return 0
  return Math.round(starRadius(mag) * 2.6 * 10) / 10
}

export function starLabel(star: Pick<NakedEyeStar, "hip" | "name" | "mag" | "bv" | "spect">): string {
  const who = star.name || `HIP ${star.hip}`
  const parts = [who, `V ${star.mag.toFixed(2)}`]
  if (star.bv != null && Number.isFinite(star.bv)) parts.push(`B−V ${star.bv.toFixed(3)}`)
  if (star.spect) parts.push(star.spect)
  return parts.join(" · ")
}

