/**
 * components/Home/naked-eye-stars.ts — Backdrop for the Moon chart
 *
 * 1625 Hipparcos stars, visual magnitude 5.00 and brighter (ESA 1997).
 * The 288 at V ≤ 3.50 are the first field; their places, V, and B−V are unchanged.
 * Places are J2000 mean positions (proper motion brought to that equinox, then left off).
 * Two Hipparcos rows at this limit have no J2000 place and are left out.
 * Constellation lines are not included. The catalogue may be used freely.
 *
 * Color is a blackbody sRGB. Ballesteros (2012) turns B−V into temperature;
 * the CIE 1931 2° observer turns that spectrum into sRGB. Along the locus:
 * O/B blue-white, A white, F yellow-white, G yellow, K orange, M red.
 * Past B−V 0.45 the chroma opens slightly so K and M read orange and red.
 * One star has no B−V and takes its color from the spectral class.
 * Size and opacity follow magnitude. A star brighter than magnitude 1
 * has a small four-point diffraction cross.
 * STAR_NAMES_BY_HIP is the proper name for a Hipparcos id (397 names, IAU,
 * with the common names already stored for the bright field kept).
 *
 * The frame is the mean ecliptic of J2000, the same frame as the planets.
 * A star is a direction on that sphere, drawn with the orrery tilt.
 * It does not move with the chart clock.
 *
 * Star identify reads those ecliptic longitudes. The named stars nearest a
 * planet are the ones with the smallest gap along the ecliptic: the shortest
 * arc, in degrees, between the star’s longitude and the planet’s heliocentric
 * longitude (`planetPlaces`). That gap is a direction on the sky from the
 * Sun’s neighborhood, not a star orbiting the planet.
 */

