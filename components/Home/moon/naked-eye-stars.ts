const DEG = Math.PI / 180
/** Mean obliquity of the ecliptic at J2000, degrees. */
const OBLIQUITY_DEG = 23.4392911
const OBLIQUITY = OBLIQUITY_DEG * DEG
const COS_OBL = Math.cos(OBLIQUITY)
const SIN_OBL = Math.sin(OBLIQUITY)

export type EclipticDirection = {
  /** Unit vector. +x is the vernal equinox, +z is ecliptic north. */
  x: number
  y: number
  z: number
  /** Degrees, 0–360. */
  lon: number
  /** Degrees, positive north. */
  lat: number
}

function wrap360(deg: number): number {
  const x = deg % 360
  return x < 0 ? x + 360 : x
}

/** Equatorial J2000 → mean ecliptic of J2000. Same sense as the planet chart. */
export function eclipticOf(raDeg: number, decDeg: number): EclipticDirection {
  const ra = raDeg * DEG
  const dec = decDeg * DEG
  const xEq = Math.cos(dec) * Math.cos(ra)
  const yEq = Math.cos(dec) * Math.sin(ra)
  const zEq = Math.sin(dec)
  const x = xEq
  const y = yEq * COS_OBL + zEq * SIN_OBL
  const z = -yEq * SIN_OBL + zEq * COS_OBL
  return {
    x,
    y,
    z,
    lon: wrap360(Math.atan2(y, x) / DEG),
    lat: Math.asin(Math.min(1, Math.max(-1, z))) / DEG,
  }
}

/**
 * Glass the orrery already uses. Tilt matches `toScreen`. The limb is a
 * unit direction, just outside Neptune's √r orbit (~186 px), not kilometres.
 * `north` lifts ecliptic latitude. It is not the chart's z×8 AU term.
 */
export const ORRERY_SKY = {
  cx: 260,
  cy: 200,
  w: 520,
  h: 400,
  limb: 216,
  tilt: 0.72,
  north: 100,
} as const

export function projectDirection(
  dir: Pick<EclipticDirection, "x" | "y" | "z">,
  glass: Pick<typeof ORRERY_SKY, "cx" | "cy" | "limb" | "tilt" | "north"> = ORRERY_SKY,
): { x: number; y: number } {
  return {
    x: glass.cx + dir.x * glass.limb,
    y: glass.cy + dir.y * glass.limb * glass.tilt - dir.z * glass.north,
  }
}

export type SkyStarDot = {
  hip: number
  name: string
  x: number
  y: number
  r: number
  fill: string
  mag: number
  bv: number | null
  spect: string
  opacity: number
  /** Hover and aria text. Does not depend on the chart clock. */
  label: string
  /** Half-length of the diffraction cross. 0 when magnitude is 1 or fainter. */
  cross: number
  /** Ecliptic longitude, degrees, mean ecliptic of J2000. */
  lon: number
}

/** One dot per catalog star, fixed on the glass. */
export function skyStarDots(glass: typeof ORRERY_SKY = ORRERY_SKY): SkyStarDot[] {
  return NAKED_EYE_STARS.map((star) => {
    const dir = eclipticOf(star.ra, star.dec)
    const at = projectDirection(dir, glass)
    return {
      hip: star.hip,
      name: star.name,
      x: Math.round(at.x * 10) / 10,
      y: Math.round(at.y * 10) / 10,
      r: starRadius(star.mag),
      fill: starFill(colorIndex(star.bv, star.spect)),
      mag: star.mag,
      bv: star.bv,
      spect: star.spect,
      opacity: starOpacity(star.mag),
      label: starLabel(star),
      cross: starCross(star.mag),
      lon: dir.lon,
    }
  })
}

export const SKY_STAR_DOTS = skyStarDots()

/** Shortest arc between two ecliptic longitudes, degrees, from 0 to 180. */
export function eclipticLongitudeGap(aDeg: number, bDeg: number): number {
  const span = Math.abs(wrap360(aDeg) - wrap360(bDeg))
  return span > 180 ? 360 - span : span
}

export type StarNear = {
  hip: number
  name: string
  mag: number
  /** Shortest ecliptic-longitude gap from the planet, degrees. */
  gap: number
  x: number
  y: number
}

const NAMED_SKY_STARS = SKY_STAR_DOTS.filter((star) => star.name)

/**
 * Named stars whose ecliptic longitude is nearest `planetLongitudeDeg`.
 * Near is `eclipticLongitudeGap` against the longitude already on each dot.
 * The chart clock does not enter this.
 */
export function nearestNamedStars(planetLongitudeDeg: number, count = 5): StarNear[] {
  if (!Number.isFinite(planetLongitudeDeg) || count <= 0) return []
  return NAMED_SKY_STARS.map((star) => ({
    hip: star.hip,
    name: star.name,
    mag: star.mag,
    gap: eclipticLongitudeGap(star.lon, planetLongitudeDeg),
    x: star.x,
    y: star.y,
  }))
    .sort((a, b) => a.gap - b.gap || a.mag - b.mag || a.hip - b.hip)
    .slice(0, count)
}
