export type PixelIconName = TaskIconName | "gem"

export function PixelIcon({ name, size = 18, className }: { name: PixelIconName; size?: number; className?: string }) {
  const rows = ICONS[name] ?? ICONS.chat
  const width = Math.max(...rows.map((row) => row.length))
  const height = rows.length
  return (
    <svg
      className={`friend-pixel${className ? ` ${className}` : ""}`}
      viewBox={`0 0 ${width} ${height}`}
      width={size}
      height={(size * height) / width}
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) =>
          PIXEL_PALETTE[cell] ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={PIXEL_PALETTE[cell]} /> : null,
        ),
      )}
    </svg>
  )
}

